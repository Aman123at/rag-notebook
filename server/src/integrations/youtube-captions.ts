/**
 * YouTube caption retrieval.
 *
 * Why the Data API cannot do this on its own: `captions.list` accepts an API key
 * and reports which caption tracks a video publishes, but `captions.download`
 * rejects API keys outright — it answers
 *   401 "API keys are not supported by this API"
 * and only accepts an OAuth token belonging to the *video owner*. So
 * YOUTUBE_API_KEY can tell us whether captions exist, never hand us their text
 * for a video we do not own. `youtube.ts` uses it for exactly that: to decide
 * whether a failed fetch is terminal ("this video has no captions") or transient
 * ("captions exist, we were blocked") — see `listCaptionTracks` there.
 *
 * How we get the text instead: we ask YouTube's own player endpoint (InnerTube,
 * `/youtubei/v1/player`) for the caption track list and download the track from
 * the `timedtext` URL it returns. That is the request the mobile apps make, so it
 * never touches the watch-page HTML that the `youtube-transcript` package
 * scraped — and the watch page is what serves a consent/bot-check interstitial
 * to datacenter IPs, which is why transcript ingestion failed in production but
 * worked from a laptop.
 *
 * Each client in INNERTUBE_CLIENTS is tried in turn; they fail independently, so
 * the chain survives any one of them being throttled or retired.
 *
 * The hard limit: YouTube gates InnerTube on IP reputation, and answers requests
 * from datacenter ranges (AWS/GCP/Azure/most VPS hosts) with a bot check —
 * playabilityStatus LOGIN_REQUIRED, reason "Sign in to confirm you're not a bot".
 * That is *not* an age gate, and treating it as one parks a perfectly ingestible
 * video in a permanent failure state; see `isBotCheck` below and the BOT_CHECK
 * branch in `youtube.ts`. No client, visitorData, or PO token reliably avoids it
 * from a datacenter IP, so `YOUTUBE_PROXY_URL` exists to send just these requests
 * (not the rest of the app's egress) through a residential proxy.
 */

import { ProxyAgent } from 'undici';

import { env } from '@/config/env.js';

const INNERTUBE_URL = 'https://www.youtube.com/youtubei/v1/player?prettyPrint=false';
const REQUEST_TIMEOUT_MS = 20_000;

/** Fallback cue length when a caption event carries no duration. */
const DEFAULT_CUE_MS = 3_000;

/**
 * Track languages we prefer when a video publishes several. A manually authored
 * track wins over an auto-generated (ASR) one in the same language; if none of
 * these languages is present we fall back to the video's own first track.
 */
const PREFERRED_LANGUAGES = ['en'] as const;

interface InnertubeClient {
  readonly id: string;
  readonly clientName: string;
  readonly clientNumber: string;
  readonly clientVersion: string;
  readonly extraContext: Readonly<Record<string, unknown>>;
  readonly userAgent: string;
}

